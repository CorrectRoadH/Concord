import assert from 'node:assert/strict';
import test from 'node:test';
import { NodeServices } from '@effect/platform-node';
import { Effect, Exit, FileSystem } from 'effect';
import { ChildProcess, ChildProcessSpawner } from 'effect/unstable/process';
import { dirname, join } from 'node:path';
import { selectGateTests } from '../../scripts/gate-selection.ts';

// @feature docs/engineering/testing/cli.md#完整门禁
test('changed gate derives old and current declarations, changed tests and shared-input selection from real Git', () => Effect.runPromise(Effect.scoped(Effect.gen(function*() {
  const fs = yield* FileSystem.FileSystem;
  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
  const root = yield* fs.makeTempDirectoryScoped({ prefix: 'concord-gate-selection-' });
  const git = (args: readonly string[]) => spawner.exitCode(ChildProcess.make('git', args, { cwd: root, stdin: 'ignore', stdout: 'ignore', stderr: 'inherit' })).pipe(Effect.map(code => assert.equal(Number(code), 0)));
  const write = Effect.fn('selection.fixture.write')(function*(file: string, text: string) {
    yield* fs.makeDirectory(dirname(join(root, file)), { recursive: true });
    yield* fs.writeFileString(join(root, file), text);
  });
  const source = '// @concord-file\n// @concord-implements docs/feature/alpha/use-case/a.md#old\nexport const f = () => 1;\n';
  const marker = (contract: string) => `// @feature ${contract}\ntest('selected', () => {});\n`;
  yield* git(['init', '-q']);
  yield* write('src/alpha.ts', source);
  yield* write('test/model/a.test.ts', marker('docs/feature/alpha/use-case/a.md'));
  yield* write('test/model/whole.test.ts', marker('docs/feature/alpha/README.md'));
  yield* write('test/model/sibling.test.ts', marker('docs/feature/alpha/use-case/b.md'));
  yield* write('test/model/other.test.ts', marker('docs/feature/other/README.md'));
  yield* write('test/model/string.test.ts', 'const text = `// @feature docs/feature/alpha/README.md`;\n');
  yield* git(['add', '.']);
  yield* git(['-c', 'user.name=Gate Test', '-c', 'user.email=gate@example.invalid', 'commit', '-qm', 'frozen inputs']);
  const initial = yield* selectGateTests(['--changed=HEAD'], root);
  assert.deepEqual(initial.files, []);
  assert.equal(initial.allFiles.length, 5);
  yield* write('concord/package.json', '{"version":"1.0.0"}');
  yield* write('concord/mods/concord/main.js', source);
  yield* write('concord/RECIPE.md', '# Published mod\n');
  const published = yield* selectGateTests(['--changed=HEAD'], root);
  assert.deepEqual(published.files, []);
  assert.deepEqual(published.selection.changedFiles, []);
  assert.deepEqual(published.selection.affectedContracts, []);
  assert.deepEqual(published.selection.ignoredFiles, ['concord/RECIPE.md', 'concord/mods/concord/main.js', 'concord/package.json']);
  yield* write('src/alpha.ts', 'export const f = () => 2;\n');
  const removed = yield* selectGateTests(['--changed=HEAD'], root);
  assert.deepEqual(removed.files, ['test/model/a.test.ts', 'test/model/whole.test.ts']);
  assert.deepEqual(removed.selection.affectedContracts, ['docs/feature/alpha/use-case/a.md']);
  yield* write('src/alpha.ts', '// @concord-file\n// @concord-implements docs/feature/alpha/cli.md\nexport const f = () => 2;\n');
  const packageChange = yield* selectGateTests(['--changed=HEAD'], root);
  assert.deepEqual(packageChange.files, ['test/model/a.test.ts', 'test/model/sibling.test.ts', 'test/model/whole.test.ts']);
  yield* write('test/model/new.test.ts', 'test("new", () => {});\n');
  const untracked = yield* selectGateTests(['--changed=HEAD'], root);
  assert.ok(untracked.files.includes('test/model/new.test.ts'));
  yield* write('test/support/shared.ts', 'export const value = 1;\n');
  const all = yield* selectGateTests(['--changed=HEAD'], root, join(root, 'reports'));
  assert.deepEqual(all.files, all.allFiles);
  assert.equal(all.selection.fullSuiteReason, 'shared input changed: test/support/shared.ts');
  assert.deepEqual(JSON.parse(yield* fs.readFileString(join(root, 'reports/selection.json'))), all.selection);
  const explicit = yield* selectGateTests(['--changed', 'HEAD', 'test/model/other.test.ts'], root);
  assert.deepEqual(explicit.files, ['test/model/other.test.ts']);
  const bad = yield* Effect.exit(selectGateTests(['--changed=no-such-gate-revision'], root));
  assert.equal(Exit.isFailure(bad), true);
})).pipe(Effect.provide(NodeServices.layer))));
